    };

  private static readonly Lazy<Dictionary<string, Dataset>> Loaded = new(ParseDatasets);

  public static bool TryGetWindow(AppIndicator indicator, out ExampleWindow window)
  {
    window = null!;

    if (!DatasetKeys.TryGetValue(indicator, out var key))
      return false;

    if (Loaded.Value.GetValueOrDefault(key) is not { } dataset
      || !dataset.Anchors.TryGetValue(indicator.ToString(), out var anchor))
      return false;

    var fromIndex = IndexOfDate(dataset, anchor.From);
    var toIndex = IndexOfDate(dataset, anchor.To);

    if (fromIndex < 0 || toIndex < fromIndex)
      return false;

    var candles = dataset.Candles[fromIndex..(toIndex + 1)];

    if (candles.Length < 2)
      return false;

    window = new ExampleWindow(dataset.Ticker, dataset.TimeFrame, candles, candles[^1].Timestamp);
    return true;
  }

  /// <summary>The full embedded series for an indicator's dataset (for tests/replays).</summary>
  internal static Candle[]? GetSeries(AppIndicator indicator) =>
    DatasetKeys.TryGetValue(indicator, out var key) ? Loaded.Value.GetValueOrDefault(key)?.Candles : null;

  private static int IndexOfDate(Dataset dataset, string dateText) =>
    Array.IndexOf(dataset.DateTexts, dateText);

  private static Dictionary<string, Dataset> ParseDatasets()
  {
    var result = new Dictionary<string, Dataset>();
    var assembly = typeof(ExampleMarketData).Assembly;

    foreach (var key in DatasetKeys.Values.Distinct())
    {
      using var stream = assembly.GetManifestResourceStream(ResourcePrefix + key + ".json");

      if (stream is null)
        continue;

      using var doc = JsonDocument.Parse(stream);
      var root = doc.RootElement;

      var ticker = root.GetProperty("ticker").GetString()!;
      var exchange = root.GetProperty("exchange").GetString();
      var timeframe = root.GetProperty("timeframe").GetString() == "Day" ? TimeFrame.Day : TimeFrame.Minute;
      var dateFormat = timeframe == TimeFrame.Day ? "yyyy-MM-dd" : "yyyy-MM-ddTHH:mm:ssZ";

      var bars = root.GetProperty("bars").EnumerateArray().ToArray();
      var candles = new Candle[bars.Length];
      var dateTexts = new string[bars.Length];

      for (var i = 0; i < bars.Length; i++)
      {
        var bar = bars[i].EnumerateArray().ToArray();

        var dateText = bar[0].GetString()!;
        var date = DateTime.Parse(dateText, CultureInfo.InvariantCulture,
          DateTimeStyles.AdjustToUniversal | DateTimeStyles.AssumeUniversal);

        dateTexts[i] = date.ToString(dateFormat, CultureInfo.InvariantCulture);

        candles[i] = new Candle(
          ticker,
          date,
          timeframe,
          bar[1].GetDecimal(),
          bar[2].GetDecimal(),
          bar[3].GetDecimal(),
          bar[4].GetDecimal(),
          bar[5].GetDecimal(),
          isCompleted: true,
          exchangeName: exchange);
      }

      var anchors = new Dictionary<string, (string From, string To)>();

      foreach (var anchor in root.GetProperty("anchors").EnumerateObject())
        anchors[anchor.Name] = (
          anchor.Value.GetProperty("from").GetString()!,
          anchor.Value.GetProperty("to").GetString()!);

      result[key] = new Dataset(ticker, timeframe, candles, dateTexts, anchors);
    }

    return result;
  }

  private sealed record Dataset(
    string Ticker,
    TimeFrame TimeFrame,
    Candle[] Candles,
    string[] DateTexts,
    Dictionary<string, (string From, string To)> Anchors);
}
