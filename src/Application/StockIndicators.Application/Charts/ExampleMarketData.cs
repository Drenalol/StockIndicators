      [AppIndicator.Ichimoku] = "aapl-daily",
      [AppIndicator.OBV] = "aapl-daily",
      [AppIndicator.Gap] = "tsla-daily",
      [AppIndicator.ATR] = "tsla-daily",
      [AppIndicator.VWAP] = "aapl-minute",
      [AppIndicator.RoundPrice] = "tsla-minute",
      [AppIndicator.Volume] = "aapl-minute",
      [AppIndicator.PriceChange] = "tsla-daily",
      [AppIndicator.CCI] = "aapl-daily",
