using System.Globalization;
using System.Text.Json;
using StockIndicators.Domain.Models.Candles;
using AppIndicator = StockIndicators.Domain.Models.Indicators.Indicator;

namespace StockIndicators.Application.Charts;

/// <summary>
/// Real historical OHLCV fixtures for the indicator example charts: daily AAPL/TSLA bars and
/// single regular-session minute series, fetched once from Alpaca and embedded as JSON.
/// Each dataset carries per-indicator anchor windows ("from"/"to" candle dates) ending on a
/// candle where that indicator's trigger fires at the example parameters, so the docs chart
/// shows exactly what a real alert looks like. Generated by an offline tool that replays the
/// production indicator handlers; regenerate the JSON together with any template default change.
/// </summary>
public static class ExampleMarketData
{
  /// <summary>A rendered example window: the candles, the ticker/timeframe to label them with
  /// and the date of the last (trigger) candle.</summary>
  public sealed record ExampleWindow(string Ticker, TimeFrame TimeFrame, Candle[] Candles, DateTime TriggerDate);

  private const string ResourcePrefix = "StockIndicators.Application.Charts.Data.market-";

  private static readonly IReadOnlyDictionary<AppIndicator, string> DatasetKeys =
